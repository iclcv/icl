  bool FilamentRenderBackend::readColor(core::Img8u &dst) const {
    if (!m_data->engine || m_data->colorRGBA.empty()) return false;
    const int W = m_data->colorSize.width, H = m_data->colorSize.height;
    dst.setChannels(3);
    dst.setSize(m_data->colorSize);
    core::Channel8u r = dst[0], g = dst[1], b = dst[2];
    const uint8_t *p = m_data->colorRGBA.data();
    for (int y = 0; y < H; ++y)
      for (int x = 0; x < W; ++x) {
        const uint8_t *px = p + (size_t(y) * W + x) * 4;  // row 0 = top
        r(x, y) = px[0]; g(x, y) = px[1]; b(x, y) = px[2];
      }
    return true;
  }

  void FilamentRenderBackend::render(const std::vector<std::shared_ptr<Node>> &nodes,
                                     const Mat &viewMatrix,
                                     const Mat &projectionMatrix) {
    if (!m_data->engine) return;
    m_data->ensureSwapChain();
    const int W = m_data->targetSize.width, H = m_data->targetSize.height;
    if (W <= 0 || H <= 0) return;

    // Apply Configurable changes on the render thread (Filament isn't thread-safe).
    if (m_data->gradingDirty.exchange(false)) m_data->rebuildColorGrading();
    if (m_data->envDirty.exchange(false)) m_data->buildEnvironment();

    // Inject ICL's calibrated projection + camera placement (the P2 recipe). The
    // near/far handed to Filament MUST match the ones baked into the matrix (they
    // drive Filament's depth-buffer range) — recover them from getProjectionMatrixGL's
    // A,B terms: near = B/(A-1), far = B/(A+1). A mismatch wrecks depth precision.
    const double A = projectionMatrix(2, 2), B = projectionMatrix(2, 3);
    double zn = B / (A - 1.0), zf = B / (A + 1.0);
    if (!(zn > 0.0) || !(zf > zn)) { zn = 1.0; zf = 100000.0; }   // guard degenerate
    m_data->fcam->setCustomProjection(toFilament(projectionMatrix), zn, zf);
    m_data->fcam->setModelMatrix(toFilament(viewMatrix.inv()));
    // Neutral exposure (~unity photometric factor) so unlit line/point colours
    // survive post-processing; light intensities are tuned to this, not to
    // physical lux (the viz3d unit scale isn't physical anyway).
    m_data->fcam->setExposure(1.0f);

    // Screen-space reflections (first-class scene feature via setSSREnabled).
    // Distances are in world units — viz3d scenes are much larger than metres,
    // so scale the ray thickness/reach up from the metric defaults.
    fl::View::ScreenSpaceReflectionsOptions ssrOpt;
    ssrOpt.enabled = m_data->ssr;
    ssrOpt.thickness = m_data->ssrThickness;
    ssrOpt.maxDistance = m_data->ssrMaxDist;
    m_data->view->setScreenSpaceReflectionsOptions(ssrOpt);

    m_data->syncLights(nodes);
    for (const auto &n : nodes) m_data->syncNode(n.get());

    m_data->colorRGBA.assign(size_t(W) * H * 4, 0);
    if (m_data->renderer->beginFrame(m_data->swapChain)) {
      m_data->renderer->render(m_data->view);
      m_data->renderer->readPixels(0, 0, W, H, fl::backend::PixelBufferDescriptor(
          m_data->colorRGBA.data(), m_data->colorRGBA.size(),
          fl::backend::PixelDataFormat::RGBA, fl::backend::PixelDataType::UBYTE));
      m_data->renderer->endFrame();
    }
    m_data->engine->flushAndWait();   // buffer descriptors consumed here
    m_data->colorSize = m_data->targetSize;
  }

